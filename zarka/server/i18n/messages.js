export const SUPPORTED_SMS_LANGUAGES = Object.keys(MESSAGES);

// msg("sn", "sentOk", { amount: 500 }) - falls back to English if a line is missing.
export function msg(language, key, vars = {}) {
  const template = MESSAGES[language]?.[key] ?? MESSAGES.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
}

export const statusLabel = (language, status) => msg(language, `status_${status}`);
